"""
AthleteOS - FastAPI backend (Step 2.1: skeleton only).

This is the WEB entry point for AthleteOS. It is deliberately separate from the
CLI developer tool in meal_planner.py: the CLI is still run with
`python3 meal_planner.py`, while the web server is run with uvicorn (see below).

This app currently exposes a health-check route at "/", and (Step 2.2) defines
the request model that the future meal-plan endpoint will accept. The POST
endpoint itself and the call to generate_meal_plan() are intentionally NOT here
yet; they come in a later step.

Run the server (from this folder):
    python3 -m uvicorn api:app --reload
Then open http://127.0.0.1:8000/ (or http://127.0.0.1:8000/docs).
"""

import logging
import re
from pathlib import Path
from typing import List, Literal, Optional, Union

from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse
from pydantic import BaseModel, Field

import memory_manager
import personal_recipes
from orchestrator import run_with_trace
from memory_integration import DEFAULT_ATHLETE_ID, update_memory_from_profile
from episodic_memory import record_episode, record_latest_plan_summary
from chat import SessionOwnershipError, chat_reply
from llm_provider import LLMProviderError, RateLimitError
from tools.ingredients_tool import parse_ingredients

logger = logging.getLogger("athleteos.api")

app = FastAPI(title="AthleteOS API", version="0.1.0")


# ----------------------------------------------------------------------
# Athlete identity (Phase 1)
# ----------------------------------------------------------------------
# An athlete_id is a UUID4 generated by the browser (see index.html), NOT a
# name - two athletes called "Rahul Sharma" get two different UUIDs and can
# never share memory. The literal "default" is still accepted so every
# pre-Phase-1 caller (the CLI, existing tests, an older cached frontend)
# keeps working against the memory that already exists under that key.
#
# This pattern is also a SAFETY boundary, not just a format check:
# memory_manager writes episodic memory to memory/episodes/<athlete_id>.json,
# so an unvalidated athlete_id arriving from the browser would be a path
# traversal risk (e.g. "../../secrets"). Constraining it to a UUID or
# "default" at the HTTP boundary - the only place untrusted input enters -
# removes that without touching memory_manager.py itself.
ATHLETE_ID_PATTERN = (
    r"^(default|[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}"
    r"-[0-9a-fA-F]{4}-[0-9a-fA-F]{12})$"
)


@app.get("/")
def read_root():
    """Health check: lets us verify the server is up and responding."""
    return {"status": "ok", "service": "AthleteOS API"}


@app.get("/app")
def serve_frontend():
    """
    Serve the single-page frontend (index.html) from the SAME origin as the
    API, so the browser's fetch() call to /meal-plan needs no CORS setup.
    This only serves a static file - it adds no business logic.
    """
    return FileResponse(Path(__file__).parent / "index.html")


# ----------------------------------------------------------------------
# Request model (Step 2.2)
# ----------------------------------------------------------------------
# Mirrors the CLI's fields and validation rules from meal_planner.py so that
# an HTTP request is validated the same way a terminal user's input is. The
# field NAMES match the profile dict that generate_meal_plan() expects, so a
# validated request can later be turned into that profile with .model_dump().

class MealPlanRequest(BaseModel):
    # --- mandatory fields (mirror the CLI's value checks, not just presence) ---
    age: int = Field(
        ge=10, le=60,
        description="Athlete's age in years.",
        examples=[22],
    )
    height_cm: float = Field(
        ge=120, le=230,
        description="Height in centimetres.",
        examples=[178],
    )
    weight_kg: float = Field(
        ge=30, le=200,
        description="Body weight in kilograms.",
        examples=[72],
    )
    sex: Literal["Male", "Female", "Other"] = Field(
        description="Athlete's sex.",
        examples=["Male"],
    )
    goal: str = Field(
        min_length=1,
        description="What the athlete wants to achieve (e.g. football performance, muscle gain, fat loss).",
        examples=["Improve football performance and some muscle gain"],
    )
    diet: Literal["Vegetarian", "Non-Vegetarian"] = Field(
        description="Dietary preference.",
        examples=["Vegetarian"],
    )
    training_days_per_week: int = Field(
        ge=1, le=7,
        description="Number of training days per week.",
        examples=[5],
    )
    training_intensity: Literal["Low", "Moderate", "High"] = Field(
        description="Typical training intensity.",
        examples=["High"],
    )
    region: str = Field(
        min_length=1,
        description="Athlete's city and/or state in India (used to suggest regionally available foods).",
        examples=["Lucknow, Uttar Pradesh"],
    )
    allergies: str = Field(
        min_length=1,
        description="Known food allergies. Use 'none' if there are no allergies.",
        examples=["none"],
    )

    # --- optional fields (absent -> None, exactly like the CLI's blank -> None) ---
    budget_per_day: Optional[str] = Field(
        default=None,
        description='Daily food budget (example: "Rs 300").',
        examples=["Rs 300"],
    )
    food_preferences: Optional[str] = Field(
        default=None,
        description="Foods the athlete likes or wants included.",
        examples=["paneer, dal, soya chunks"],
    )
    foods_to_avoid: Optional[str] = Field(
        default=None,
        description="Foods the athlete wants to avoid (separate from allergies).",
        examples=["heavy fried food"],
    )
    notes: Optional[str] = Field(
        default=None,
        description="Additional context for the meal planner.",
        examples=["Match tomorrow at 9 AM; needs easy digestion"],
    )
    available_ingredients: Optional[str] = Field(
        default=None,
        description=(
            "Optional: ingredients the athlete already has at home. Used to bias "
            "food selection toward what is on hand; never overrides allergies, "
            "diet, foods to avoid, or nutritional needs. Not remembered between "
            "requests - it describes today's kitchen, not a standing preference."
        ),
        examples=["rice, dal, tomatoes, curd, peanuts"],
    )

    # --- identity (Phase 1) ---
    # Deliberately NOT part of the athlete profile itself: it selects WHOSE
    # memory to read/write, it is not a nutrition input. create_meal_plan()
    # pops it back off before the profile reaches the planner, so the profile
    # dict handed to generate_meal_plan() is exactly the shape it always was.
    athlete_id: str = Field(
        default=DEFAULT_ATHLETE_ID,
        pattern=ATHLETE_ID_PATTERN,
        description="UUID4 identifying whose stored memory this request belongs to.",
        examples=["3f2a1c8e-5b4d-4e7a-9c1f-2d6b8e0a4c73"],
    )

    # --- plan duration (Step 6: multi-day planning) ---
    # Default 1 so every existing caller (old frontend, tests, the CLI-style
    # direct calls) behaves EXACTLY as before - the field simply didn't exist
    # for them, and 1 reproduces that. The UI currently only offers 1 or 7,
    # but the underlying generator (meal_planner.mock_provider_multi_day)
    # already handles any day count generically, so the upper bound here is
    # a sanity ceiling for a future 14/28-day option, not a hint that those
    # are wired into the UI yet.
    duration_days: int = Field(
        default=1, ge=1, le=28,
        description="How many days of meal plans to generate (currently 1 or 7 in the UI).",
        examples=[1, 7],
    )


# ----------------------------------------------------------------------
# Response models (Step 2.4)
# ----------------------------------------------------------------------
# These describe the EXACT JSON that generate_meal_plan() already returns.
# They add no logic and change no output - they just make the response
# contract explicit so FastAPI can document and validate it.

class NutritionInfo(BaseModel):
    basis: str
    kcal: float
    protein_g: float
    carbs_g: float
    fat_g: float
    source: str
    source_ref: str


class Ingredient(BaseModel):
    item: str
    quantity: str
    nutrition: Optional[NutritionInfo] = None


class Resource(BaseModel):
    type: str
    title: str
    url: str
    item: str


class Meal(BaseModel):
    meal: str
    ingredients: List[Ingredient]
    calories: int
    protein_g: int
    carbs_g: int
    fats_g: int
    reasoning: str
    resources: List[Resource]


class DaySummary(BaseModel):
    total_calories: int
    total_protein_g: int
    total_carbs_g: int
    total_fats_g: int
    notes: str


class MealPlanResponse(BaseModel):
    confidence_score: float
    confidence_reason: List[str]
    day_summary: DaySummary
    meals: List[Meal]
    disclaimer: str


# --- Multi-day response (Step 6) ---
# A structurally distinct shape (top-level "days" list instead of top-level
# "day_summary"/"meals") rather than overloading MealPlanResponse with
# optional multi-day fields - so a duration_days=1 request keeps returning
# exactly the MealPlanResponse shape every existing client already expects,
# with zero new optional fields for it to ignore. confidence_score/reason
# are hoisted to the top level (not repeated per day) since they reflect how
# complete the ATHLETE'S profile is, not anything that varies day to day.

class DayPlan(BaseModel):
    day: int
    day_summary: DaySummary
    meals: List[Meal]


class MultiDayMealPlanResponse(BaseModel):
    duration_days: int
    confidence_score: float
    confidence_reason: List[str]
    days: List[DayPlan]
    disclaimer: str


# ----------------------------------------------------------------------
# Meal-plan endpoint (Step 2.3, response_model added in Step 2.4,
# Profile/Preference memory in Stage 1, Episodic memory in Stage 2,
# Agent v1 orchestrator wired in as the real request coordinator)
# ----------------------------------------------------------------------
# Still thin: FastAPI validates the body against MealPlanRequest, then
# hands the whole request to orchestrator.run_with_trace() - which owns
# loading/merging memory, RAG retrieval, tool decisions, and calling
# generate_meal_plan() (all internally, all unchanged). This endpoint keeps
# ONLY the two write-back steps that the orchestrator deliberately never
# does (see orchestrator.py's docstring): persisting Profile/Preference
# memory and recording the episode - both run exactly once, after the
# orchestrator returns successfully. generate_meal_plan() itself, the
# request/response schemas, and everything the endpoint returns are all
# unchanged.

@app.post("/meal-plan", response_model=Union[MealPlanResponse, MultiDayMealPlanResponse])
def create_meal_plan(request: MealPlanRequest):
    payload = request.model_dump()
    # Identity selects WHOSE memory this request touches; it is not a
    # nutrition input, so it is removed before the profile continues down a
    # pipeline that has never seen (and does not need) this field.
    athlete_id = payload.pop("athlete_id")
    # Plan duration (Step 6) is likewise not a nutrition input - it selects
    # HOW MANY days to generate, not anything about the athlete.
    duration_days = payload.pop("duration_days")
    profile = payload                                # validated model -> the profile dict
    trace = run_with_trace(profile, athlete_id, days=duration_days)  # Agent v1: memory + RAG + tools + generation
    update_memory_from_profile(trace["merged_profile"], athlete_id)  # remember this athlete's latest info
    # Episodic memory's schema (episodic_memory.create_episode) reads a
    # single day_summary/meals shape - exactly what a duration_days=1 plan
    # returns, so episodic HISTORY (the append-only "RECENT MEAL PLANS"
    # trend chat already shows) stays single-day-only, unchanged from
    # before this feature.
    if duration_days == 1:
        record_episode(trace["merged_profile"], trace["plan"], athlete_id)  # log a short summary of this generation
    # "latest_plan" (Step 9) is a SEPARATE, update-in-place summary - not
    # episodic history - recorded for EVERY successful generation regardless
    # of duration, so chat always has the most recently generated plan
    # available (see episodic_memory.record_latest_plan_summary()). A new
    # generation overwrites it; older plans are never accumulated here.
    record_latest_plan_summary(trace["merged_profile"], trace["plan"], athlete_id)
    return trace["plan"]


# ----------------------------------------------------------------------
# Saved profile lookup (used by the frontend when switching athletes)
# ----------------------------------------------------------------------
# Read-only: returns whatever is already stored in Profile/Preference memory
# for this athlete_id, exactly as memory_integration.py already categorizes
# it (PROFILE_FIELDS + PREFERENCE_FIELDS). No new memory logic - this is a
# straight passthrough of memory_manager.get(), so an athlete with nothing
# stored yet gets every field back as null (the frontend then leaves the
# form at its normal defaults). "goal", "training_days_per_week",
# "training_intensity", and "notes" are deliberately absent, exactly as
# memory_integration.py already excludes them - they describe a single
# request, not a stable athlete fact, and stay ephemeral per-visit.

class AthleteProfileResponse(BaseModel):
    age: Optional[int] = None
    height_cm: Optional[float] = None
    weight_kg: Optional[float] = None
    sex: Optional[Literal["Male", "Female", "Other"]] = None
    diet: Optional[Literal["Vegetarian", "Non-Vegetarian"]] = None
    region: Optional[str] = None
    allergies: Optional[str] = None
    budget_per_day: Optional[str] = None
    food_preferences: Optional[str] = None
    foods_to_avoid: Optional[str] = None


@app.get("/athlete/{athlete_id}/profile", response_model=AthleteProfileResponse)
def get_athlete_profile(athlete_id: str):
    if not re.match(ATHLETE_ID_PATTERN, athlete_id):
        raise HTTPException(status_code=422, detail="athlete_id must be a UUID4 or 'default'.")
    stored_profile = memory_manager.get("profile", athlete_id) or {}
    stored_preference = memory_manager.get("preference", athlete_id) or {}
    return {**stored_profile, **stored_preference}


# ----------------------------------------------------------------------
# Personal recipes ("My Recipes")
# ----------------------------------------------------------------------
# Athlete-saved homemade/family recipes - persistent, strictly keyed by
# athlete_id (never by display name), stored via memory_manager's existing
# "recipes" category (personal_recipes.py). This endpoint layer does NO
# safety filtering itself - it only stores/retrieves what the athlete typed.
# Whether a saved recipe is safe to ever OFFER in a generated plan is
# decided later, at generation/chat time, by
# meal_planner.classify_personal_recipes() - saving a recipe never implies
# it will be recommended.

class RecipeCreate(BaseModel):
    name: str = Field(min_length=1, description="e.g. \"Mom's Chicken Curry\"")
    ingredients: str = Field(
        min_length=1,
        description="Comma or newline separated, e.g. \"Chicken, Onion, Tomato, Ginger, Garlic, Spices\"",
    )
    method: Optional[str] = Field(default=None, description="Preparation/method (optional).")
    notes: Optional[str] = Field(default=None, description="Optional notes.")
    servings: Optional[str] = Field(default=None, description="Optional, e.g. \"4 servings\".")


class Recipe(BaseModel):
    id: str
    name: str
    ingredients: List[str]
    method: Optional[str] = None
    notes: Optional[str] = None
    servings: Optional[str] = None
    created_at: float


@app.get("/athlete/{athlete_id}/recipes", response_model=List[Recipe])
def get_recipes(athlete_id: str):
    if not re.match(ATHLETE_ID_PATTERN, athlete_id):
        raise HTTPException(status_code=422, detail="athlete_id must be a UUID4 or 'default'.")
    return personal_recipes.list_recipes(athlete_id)


@app.post("/athlete/{athlete_id}/recipes", response_model=Recipe)
def create_recipe(athlete_id: str, payload: RecipeCreate):
    if not re.match(ATHLETE_ID_PATTERN, athlete_id):
        raise HTTPException(status_code=422, detail="athlete_id must be a UUID4 or 'default'.")
    # Same comma/newline ingredient parsing home-ingredients already uses -
    # no second parsing scheme for what is, structurally, the same kind of
    # "list of foods typed as free text" input.
    ingredients = parse_ingredients(payload.ingredients)
    if not ingredients:
        raise HTTPException(status_code=422, detail="At least one ingredient is required.")
    return personal_recipes.add_recipe(
        athlete_id, payload.name, ingredients, payload.method, payload.notes, payload.servings,
    )


@app.delete("/athlete/{athlete_id}/recipes/{recipe_id}")
def remove_recipe(athlete_id: str, recipe_id: str):
    if not re.match(ATHLETE_ID_PATTERN, athlete_id):
        raise HTTPException(status_code=422, detail="athlete_id must be a UUID4 or 'default'.")
    deleted = personal_recipes.delete_recipe(athlete_id, recipe_id)
    if not deleted:
        raise HTTPException(status_code=404, detail="Recipe not found.")
    return {"deleted": True}


# ----------------------------------------------------------------------
# Chat endpoint ("Ask AthleteOS")
# ----------------------------------------------------------------------
# Thin wrapper around chat.chat_reply() - all the actual work (memory
# lookup, RAG retrieval, prompt assembly, the OpenRouter call, and the one
# narrow preference-saving rule) lives in chat.py, reusing the existing
# pipeline components. This endpoint only translates HTTP <-> that function,
# and turns a provider failure (e.g. no OPENROUTER_API_KEY configured) into
# a clean 503 instead of a raw 500 traceback.

class ChatMessage(BaseModel):
    role: Literal["user", "assistant"]
    content: str


class ChatRequest(BaseModel):
    message: str = Field(min_length=1, description="The athlete's chat message.")
    athlete_id: str = Field(
        default=DEFAULT_ATHLETE_ID,
        pattern=ATHLETE_ID_PATTERN,
        description="UUID4 identifying whose stored memory this conversation may read.",
    )
    session_id: Optional[str] = Field(
        default=None,
        description=(
            "Ephemeral conversation id from the browser. A new one is generated on "
            "page load and whenever the athlete is switched, so a transcript never "
            "survives a reload and never crosses between athletes."
        ),
    )
    history: List[ChatMessage] = Field(
        default_factory=list,
        description="Recent prior turns in this conversation, oldest first.",
    )


class MemoryUpdate(BaseModel):
    field: str
    value: str


class ChatResponse(BaseModel):
    reply: str
    memory_updated: Optional[MemoryUpdate] = None


@app.post("/chat", response_model=ChatResponse)
def chat(request: ChatRequest):
    try:
        result = chat_reply(
            request.message,
            athlete_id=request.athlete_id,
            history=[turn.model_dump() for turn in request.history],
            session_id=request.session_id,
        )
    except SessionOwnershipError as exc:
        # A session_id already in use by a DIFFERENT athlete - refuse rather
        # than answer, so one athlete's conversation can never be continued
        # under another athlete's identity/memory. str(exc) here is already
        # a deliberately-authored, user-appropriate message - not leaked
        # internals - so it's safe to pass straight through.
        raise HTTPException(status_code=409, detail=str(exc)) from exc
    except RateLimitError as exc:
        # OpenRouter's free-tier model sits behind a shared, oversubscribed
        # pool - a 429 here is an external capacity limit, not a bug (see
        # llm_provider.RateLimitError's docstring for the live-reproduced
        # root cause). Told apart from the generic LLMProviderError branch
        # below so the athlete gets an honest, specific reason instead of
        # the same catch-all message used for a missing key or a network
        # failure. No retry here on purpose - retrying against an already-
        # oversubscribed shared pool would only add to the congestion.
        logger.warning("chat: OpenRouter rate limit hit for athlete_id=%r: %s", request.athlete_id, exc)
        raise HTTPException(
            status_code=503,
            detail="AthleteOS is temporarily busy. Please try again in a moment.",
        ) from exc
    except LLMProviderError as exc:
        # The real cause (missing API key, network failure, malformed
        # provider response, etc.) is logged server-side for debugging, but
        # never sent to the athlete - the raw exception text can contain
        # internal identifiers (env var names, provider error payloads) that
        # have no business reaching a chat bubble. See chat.py's module
        # docstring for the audit finding this closes out.
        logger.error("chat: LLM provider failed for athlete_id=%r: %s", request.athlete_id, exc)
        raise HTTPException(
            status_code=503,
            detail="Ask AthleteOS isn't available right now. Please try again in a moment.",
        ) from exc
    return result
